# Bakes the random numbers the Python original draws from numpy for the glitter on the fins
# into Sources/BettaLite/Tables.swift, so the fins sparkle where they did in the original.
# Only needed if betta_fish.py changes:
#
#   python tools/export_tables.py        (needs numpy and pygame-ce: pip install numpy pygame-ce)

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# the original, betta_fish.py, from github.com/dwcminh/ascii-art: cloned beside this repository, or
# wherever BETTA_FISH_PY says
ORIGINAL = Path(os.environ.get("BETTA_FISH_PY", HERE.parent.parent / "ascii-art" / "BETTA-FISH" / "betta_fish.py"))
if not ORIGINAL.exists():
    sys.exit(f"betta_fish.py isn't at {ORIGINAL}: clone https://github.com/dwcminh/ascii-art beside this repository, "
             "or set BETTA_FISH_PY to where it is")
sys.path.insert(0, str(ORIGINAL.parent))
import betta_fish as b  # noqa: E402


def arr(name, values):
    flat = [float(v) for v in b.np.asarray(values, float).ravel()]
    body = ",".join(f"{v:.9g}" for v in flat)
    return f"let {name}: [Float] = [{body}]\n"


def ints(name, values):
    body = ",".join(str(int(v)) for v in b.np.asarray(values).ravel())
    return f"let {name}: [Int] = [{body}]\n"


out = ["// Generated by tools/export_tables.py from betta_fish.py. Do not edit.\n\n"]
for name, (at, speed, phase) in (("TAIL", b.TAIL_GLITTER), ("BACK", b.BACK_GLITTER), ("BELLY", b.BELLY_GLITTER)):
    out.append(ints(f"{name}_GLITTER_AT", at))
    out.append(arr(f"{name}_GLITTER_SPEED", speed))
    out.append(arr(f"{name}_GLITTER_PHASE", phase))

(HERE.parent / "Sources" / "BettaLite" / "Tables.swift").write_text("".join(out))
print("wrote Tables.swift")
